import fs from 'node:fs';
import path from 'node:path';
import OpenAI from 'openai';
import {MALCO_PROMPTS} from './lib/prompts.js';
import {config, requestRef, sessionDir, readJSON, writeJSON, failure, httpError, lockSession, liveSettings, jsonObject} from './lib/runtime.js';

export function buildMessages(predictions) {
  // Numerical contributions are explicitly transmitted, in log-odds units, not just image filenames.
  return [{role:'system',content:MALCO_PROMPTS.SYSTEM_IDENTITY},
    {role:'user',content:JSON.stringify({predictions,explanation:'SHAP values are model associations in log-odds, not causal effects.'})+'\n'+MALCO_PROMPTS.INITIAL_TASK}];
}
export async function GET(request,context={}) {
  let unlock;
  try {
    const ref=await requestRef(request,context), cfg=config(), dir=sessionDir(ref,cfg);
    unlock=lockSession(dir);
    const source=path.join(dir,'predictions.json');
    if(!fs.existsSync(source)) throw httpError('Complete patient prediction first',409);
    const file=path.join(dir,'chat.json');
    if(!fs.existsSync(file)) writeJSON(file,buildMessages(readJSON(source).predictions));
    return Response.json({referenceKey:ref,mode:cfg.mode,messages:readJSON(file)});
  } catch(e) {return failure(e);} finally {unlock?.();}
}
export async function POST(request,context={}) {
  let unlock;
  try {
    const ref=await requestRef(request,context), cfg=config(), dir=sessionDir(ref,cfg);
    const {message}=await jsonObject(request);
    if(typeof message!=='string' || !message.trim() || message.length>10000) throw httpError('message must contain 1–10000 characters');
    unlock=lockSession(dir);
    if(fs.existsSync(path.join(dir,'review.json'))) throw httpError('Session has been reviewed; start a new session to continue chatting',409);
    const file=path.join(dir,'chat.json');
    if(!fs.existsSync(file)) throw httpError('Initialize chat first',409);
    const history=readJSON(file), messages=[...history,{role:'user',content:message}];
    let response;
    if(cfg.mode==='demo') {
      response=(async function*(){yield {choices:[{delta:{content:'[OFFLINE DEMO] Message received. This fixed test response is not clinical advice and was not generated by an LLM.'},finish_reason:'stop'}]};})();
    } else {
      const model=process.env.CHAT_MODEL;
      if(!model) throw httpError('Set CHAT_MODEL for live mode',503);
      const client=new OpenAI({...liveSettings('CHAT'),timeout:60000,maxRetries:0});
      response=await client.chat.completions.create({model,messages,temperature:.2,stream:true});
    }
    const release=unlock; unlock=undefined;
    const encoder=new TextEncoder();
    const stream=new ReadableStream({async start(controller){
      let full='', finishReason;
      try {
        for await(const chunk of response) {
          const reason=chunk.choices?.[0]?.finish_reason;
          if(reason) finishReason=reason;
          const text=chunk.choices?.[0]?.delta?.content || '';
          if(text) {full+=text; controller.enqueue(encoder.encode(`data: ${JSON.stringify({type:'delta',text,mode:cfg.mode})}\n\n`));}
        }
        if(!full.trim()) throw new Error('Empty model response');
        if(finishReason!=='stop') throw new Error(`Incomplete model response: ${finishReason || 'missing completion reason'}`);
        messages.push({role:'assistant',content:full});
        writeJSON(file,messages);
        fs.writeFileSync(path.join(dir,'chatlog.txt'),messages.map(m=>`${m.role.toUpperCase()}: ${m.content}`).join('\n\n'),'utf8');
        controller.enqueue(encoder.encode(`data: ${JSON.stringify({type:'done'})}\n\n`));
        controller.close();
      } catch(e) {
        console.error('Chat stream failed:',e.message);
        try {controller.enqueue(encoder.encode(`data: ${JSON.stringify({type:'error',message:'Chat did not complete; retry the message.'})}\n\n`));controller.close();} catch {}
      } finally {release();}
    }});
    return new Response(stream,{headers:{'Content-Type':'text/event-stream; charset=utf-8','Cache-Control':'no-cache'}});
  } catch(e) {console.error('Chat failed:',e.message);return failure(e);} finally {unlock?.();}
}
